#!/usr/bin/env python3
"""Generate SkyPoint/catalog_data.h from HYG v4.1 (CC BY-SA 4.0), the HYG DSO list
(Messier objects) and Stellarium's 'modern' constellation lines (GPL-2.0+).

Usage: gen_catalog.py hygdata_v41.csv dso.csv stellarium_modern_index.json out.h
"""
import csv, json, sys, math

MAG_LIMIT = 5.0
hyg, dso, sc, out = sys.argv[1:5]

stars = {}
by_hip = {}
with open(hyg, newline='') as f:
    for r in csv.DictReader(f):
        if r['proper'] == 'Sol' or not r['mag']:
            continue
        hip = int(r['hip']) if r['hip'] else 0
        mag = float(r['mag'])
        rec = dict(hip=hip, ra=float(r['ra']) * 15.0, dec=float(r['dec']), mag=mag,
                   ci=float(r['ci']) if r['ci'] else 0.6, name=r['proper'],
                   con=r['con'], dist=float(r['dist']) if r['dist'] else 0.0,
                   bayer=r['bayer'], spect=r['spect'][:3])
        if hip:
            if hip not in by_hip or mag < by_hip[hip]['mag']:
                by_hip[hip] = rec
        if mag <= MAG_LIMIT:
            key = hip if hip else ('id', r['id'])
            stars[key] = rec

cons = json.load(open(sc))['constellations']
line_hips = set()
for c in cons:
    for pl in c['lines']:
        for h in pl:
            if isinstance(h, int):
                line_hips.add(h)
for h in line_hips:
    if h in by_hip and h not in stars:
        stars[h] = by_hip[h]

slist = sorted(stars.values(), key=lambda s: s['mag'])
index = {s['hip']: i for i, s in enumerate(slist) if s['hip']}

# names: proper name, else nothing. Keep only names of reasonably bright stars on screen.
names = []
def cstr(s):
    out=''
    for ch in s:
        if ch in '\\"': out+='\\'+ch
        elif ord(ch)<128: out+=ch
        else: out+=''.join('\\x%02X'%b for b in ch.encode('utf-8'))+'""'
    return '"' + out + '"'

GREEK = {'Alp':'\u03b1','Bet':'\u03b2','Gam':'\u03b3','Del':'\u03b4','Eps':'\u03b5','Zet':'\u03b6','Eta':'\u03b7',
         'The':'\u03b8','Iot':'\u03b9','Kap':'\u03ba','Lam':'\u03bb','Mu':'\u03bc','Nu':'\u03bd','Xi':'\u03be','Omi':'\u03bf',
         'Pi':'\u03c0','Rho':'\u03c1','Sig':'\u03c3','Tau':'\u03c4','Ups':'\u03c5','Phi':'\u03c6','Chi':'\u03c7','Psi':'\u03c8','Ome':'\u03c9'}

segs = []
con_meta = []
for c in cons:
    abbr = c['id'].split()[-1]
    name = c['common_name'].get('native') or c['common_name'].get('english')
    eng = c['common_name'].get('english', name)
    first = len(segs)
    sx = sy = sz = 0.0
    n = 0
    for pl in c['lines']:
        pl = [h for h in pl if isinstance(h, int)]
        for a, b in zip(pl, pl[1:]):
            if a in index and b in index:
                segs.append((index[a], index[b]))
                for h in (a, b):
                    s = slist[index[h]]
                    ra, de = math.radians(s['ra']), math.radians(s['dec'])
                    sx += math.cos(de) * math.cos(ra); sy += math.cos(de) * math.sin(ra); sz += math.sin(de); n += 1
    if n:
        l = math.sqrt(sx*sx+sy*sy+sz*sz)
        cra = math.degrees(math.atan2(sy, sx)) % 360
        cde = math.degrees(math.asin(sz / l))
    else:
        cra = cde = 0
    con_meta.append((abbr, name, eng, first, len(segs) - first, cra, cde))

# Messier objects
TYPES = {'Gxy':'Galaxy','OC':'Open cluster','Glc':'Globular cluster','Pln':'Planetary nebula',
         'Neb':'Nebula','Snr':'Supernova remnant','*Ass':'Star cloud','DN':'Dark nebula','BN':'Nebula',
         'EN':'Emission nebula','RN':'Reflection nebula','C+N':'Cluster + nebula','**':'Double star',
         'GxyCld':'Galaxy cloud','MWSC':'Star cloud','Ast':'Asterism'}
MNAMES = {1:'Crab Nebula',8:'Lagoon Nebula',13:'Hercules Cluster',16:'Eagle Nebula',17:'Omega Nebula',
          20:'Trifid Nebula',27:'Dumbbell Nebula',31:'Andromeda Galaxy',33:'Triangulum Galaxy',42:'Orion Nebula',
          44:'Beehive Cluster',45:'Pleiades',51:'Whirlpool Galaxy',57:'Ring Nebula',64:'Black Eye Galaxy',
          81:"Bode's Galaxy",82:'Cigar Galaxy',97:'Owl Nebula',101:'Pinwheel Galaxy',104:'Sombrero Galaxy',
          11:'Wild Duck Cluster',7:"Ptolemy's Cluster",6:'Butterfly Cluster',22:'Sagittarius Cluster',
          24:'Sagittarius Star Cloud',39:'',41:'',35:'',3:'',5:'',92:''}
dsos = []
with open(dso, newline='') as f:
    for r in csv.DictReader(f):
        m = None
        if r['cat1'] == 'M': m = r['id1']
        elif r['cat2'] == 'M': m = r['id2']
        if not m: continue
        m = int(float(m))
        mag = float(r['mag']) if r['mag'] else 9.0
        dsos.append((m, float(r['ra']) * 15.0, float(r['dec']), mag, TYPES.get(r['type'], r['type']),
                     MNAMES.get(m, '')))
seen = set(); dl = []
for d in sorted(dsos, key=lambda d: d[3]):
    if d[0] in seen: continue
    seen.add(d[0]); dl.append(d)
dl.sort(key=lambda d: d[0])

with open(out, 'w', encoding='utf-8') as o:
    o.write('// Generated by tools/gen_catalog.py - do not edit.\n')
    o.write('// Stars: HYG database v4.1 (astronexus, CC BY-SA 4.0). Messier: HYG DSO list.\n')
    o.write('// Constellation lines: Stellarium "modern" sky culture (GPL-2.0-or-later).\n#pragma once\n#include <stdint.h>\n\n')
    o.write('struct CatStar { float ra, dec; int16_t mag100; int16_t ci100; uint16_t name; uint8_t con; uint8_t bayer; float dist_pc; };\n')
    o.write('struct CatCon { const char *abbr, *name, *english; uint16_t first, count; float ra, dec; };\n')
    o.write('struct CatDso { uint8_t m; float ra, dec; int16_t mag100; const char *type, *name; };\n\n')
    conidx = {c[0].upper(): i for i, c in enumerate(con_meta)}
    # name table
    ntab = ['']
    def nid(s):
        if not s: return 0
        ntab.append(s); return len(ntab) - 1
    greek_ids = {}
    o.write(f'static const uint16_t CAT_NSTARS = {len(slist)};\nstatic const CatStar CAT_STARS[] = {{\n')
    bayer_list = ['']
    for s in slist:
        con = conidx.get(s['con'].upper(), 255)
        b = GREEK.get(s['bayer'].split('-')[0], '') if s['bayer'] else ''
        if b and b not in bayer_list: bayer_list.append(b)
        bi = bayer_list.index(b) if b else 0
        o.write(f"  {{{s['ra']:.5f}f,{s['dec']:.5f}f,{round(s['mag']*100)},{round(s['ci']*100)},{nid(s['name'])},{con},{bi},{s['dist']:.2f}f}},\n")
    o.write('};\n\n')
    # J2000 unit vectors, int16 (1/32767), so the firmware needs no per-star trig or RAM copy
    o.write('static const int16_t CAT_VEC[][3] = {\n')
    for s_ in slist:
        ra, de = math.radians(s_['ra']), math.radians(s_['dec'])
        v = (math.cos(de)*math.cos(ra), math.cos(de)*math.sin(ra), math.sin(de))
        o.write('  {%d,%d,%d},\n' % tuple(round(c*32767) for c in v))
    o.write('};\n\n')
    o.write('static const char *const CAT_NAMES[] = {' + ','.join(cstr(n) for n in ntab) + '};\n')
    o.write('static const char *const CAT_GREEK[] = {' + ','.join(cstr(n) for n in bayer_list) + '};\n\n')
    o.write(f'static const uint16_t CAT_NSEGS = {len(segs)};\nstatic const uint16_t CAT_SEGS[][2] = {{\n')
    for i in range(0, len(segs), 8):
        o.write('  ' + ','.join(f'{{{a},{b}}}' for a, b in segs[i:i+8]) + ',\n')
    o.write('};\n\n')
    o.write(f'static const uint8_t CAT_NCONS = {len(con_meta)};\nstatic const CatCon CAT_CONS[] = {{\n')
    for c in con_meta:
        o.write(f'  {{{cstr(c[0])},{cstr(c[1])},{cstr(c[2])},{c[3]},{c[4]},{c[5]:.3f}f,{c[6]:.3f}f}},\n')
    o.write('};\n\n')
    o.write(f'static const uint8_t CAT_NDSO = {len(dl)};\nstatic const CatDso CAT_DSO[] = {{\n')
    for d in dl:
        o.write(f'  {{{d[0]},{d[1]:.4f}f,{d[2]:.4f}f,{round(d[3]*100)},{cstr(d[4])},{cstr(d[5])}}},\n')
    o.write('};\n')
if len(sys.argv) > 5:
    # compact JS catalogue for the Android app: same data as the firmware
    import json
    names = ['']; nidx = {}
    def nm(x):
        if not x: return 0
        if x not in nidx: nidx[x] = len(names); names.append(x)
        return nidx[x]
    conidx = {c[0].upper(): i for i, c in enumerate(con_meta)}
    js = {
        'stars': [[round(s_['ra'], 4), round(s_['dec'], 4), round(s_['mag'], 2), round(s_['ci'], 2), nm(s_['name']),
                   conidx.get(s_['con'].upper(), -1), GREEK.get(s_['bayer'].split('-')[0], '') if s_['bayer'] else '',
                   round(s_['dist'], 1)] for s_ in slist],
        'names': names,
        'segs': [x for ab in segs for x in ab],
        'cons': [[c[0], c[1], round(c[5], 2), round(c[6], 2)] for c in con_meta],
        'dso': [[d[0], round(d[1], 3), round(d[2], 3), round(d[3], 1), d[4], d[5]] for d in dl],
    }
    with open(sys.argv[5], 'w', encoding='utf-8') as o:
        o.write('// Generated by tools/gen_catalog.py. Stars: HYG v4.1 (CC BY-SA 4.0). Figures: Stellarium (GPL-2.0+).\n')
        o.write('window.CATALOG=' + json.dumps(js, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'{len(slist)} stars, {len(segs)} segments, {len(con_meta)} constellations, {len(dl)} Messier', file=sys.stderr)

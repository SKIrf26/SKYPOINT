#!/usr/bin/env python3
"""Constellation artwork for the Android app.

Usage: gen_art.py stellarium_modern_index.json illustrations_dir hygdata_v41.csv out_www_dir [all]

By default only the well-known figures in MAIN get a drawing; pass "all" for all 85.

Takes Stellarium's "modern" sky-culture illustrations (Johan Meuris, Free Art License 1.3),
turns each greyscale drawing into a tinted RGBA WebP whose alpha is the drawing's brightness,
and writes lib/art.js with, per constellation, the image size and its three anchor stars
(pixel position + J2000 RA/Dec looked up by HIP number in HYG), so the app can pin each
drawing to the sky with an affine transform."""
import csv, json, os, sys
from PIL import Image

idx, ill, hyg, out = sys.argv[1:5]
ALL = len(sys.argv) > 5 and sys.argv[5] == 'all'
# The famous ones: both dippers (Ursa Major / Minor), the zodiac, Orion and the other figures
# most people learn first. Edit this list to add or drop drawings.
MAIN = set('''UMa UMi Ari Tau Gem Cnc Leo Vir Lib Sco Sgr Cap Aqr Psc Ori Cas Cyg Lyr Aql Peg
              And Per CMa Dra Her Boo Aur Cep Cen Cru'''.split())
hip = {}
with open(hyg, newline='') as f:
    for r in csv.DictReader(f):
        if r['hip']:
            hip[int(r['hip'])] = (float(r['ra']) * 15.0, float(r['dec']))
TINT = (178, 226, 236)   # pale glacier, close to the app's accent but softer
os.makedirs(os.path.join(out, 'art'), exist_ok=True)
rows, total = [], 0
for c in json.load(open(idx))['constellations']:
    im = c.get('image')
    if not im: continue
    abbr = c['id'].split()[-1]
    if not ALL and abbr not in MAIN: continue
    try:
        anchors = [[a['pos'][0], a['pos'][1], *hip[a['hip']]] for a in im['anchors']]
    except KeyError:
        print('skip (anchor not in HYG):', abbr); continue
    src = Image.open(os.path.join(ill, os.path.basename(im['file']))).convert('L')
    sw, sh = im['size']
    lo, hi = src.getextrema()
    k = 255.0 / max(1, hi)
    # lines are the brightest pixels; the soft grey fills fall away so the sky stays readable
    a = src.point(lambda v: min(255, int(255 * ((v * k) / 255.0) ** 2.6)))
    rgba = Image.merge('RGBA', [Image.new('L', src.size, TINT[0]), Image.new('L', src.size, TINT[1]), Image.new('L', src.size, TINT[2]), a])
    name = os.path.splitext(os.path.basename(im['file']))[0] + '.webp'
    path = os.path.join(out, 'art', name)
    rgba.save(path, 'WEBP', quality=78, method=6, alpha_quality=80)
    total += os.path.getsize(path)
    # anchors are in the declared size's pixel space; the PNG may be stored at another size
    rows.append([abbr, 'art/' + name, sw, sh, [[round(x, 1), round(y, 1), round(ra, 4), round(de, 4)] for x, y, ra, de in anchors]])
with open(os.path.join(out, 'lib', 'art.js'), 'w') as f:
    f.write('/* Constellation illustrations: Johan Meuris for Stellarium, Free Art License 1.3. Generated by tools/gen_art.py */\n')
    f.write('window.ART=' + json.dumps(rows, separators=(',', ':')) + ';\n')
print(len(rows), 'drawings,', total // 1024, 'KB')
